const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
const MONTHS = {
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
  bn: ["জানুয়ারি", "ফেব্রুয়ারি", "মার্চ", "এপ্রিল", "মে", "জুন", "জুলাই", "আগস্ট", "সেপ্টেম্বর", "অক্টোবর", "নভেম্বর", "ডিসেম্বর"],
};

const I18N = {
  lang: "bn",
  digits: "bn",
  t(key, vars) {
    const table = STRINGS[this.lang] || STRINGS.en;
    let text = key.split(".").reduce((o, k) => (o ? o[k] : undefined), table);
    if (text === undefined) text = key.split(".").reduce((o, k) => (o ? o[k] : undefined), STRINGS.en);
    if (text === undefined) return key;
    if (typeof text === "string" && vars) {
      text = text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? String(vars[name]) : `{${name}}`));
    }
    return typeof text === "string" ? this.d(text) : text;
  },
  /* Apply the digit preference to any Bengali text: Latin <-> Bengali digits. */
  d(text) {
    if (this.lang !== "bn" || text === null || text === undefined) return text;
    const s = String(text);
    if (this.digits === "bn") return s.replace(/[0-9]/g, (c) => BN_DIGITS[+c]);
    return s.replace(/[০-৯]/g, (c) => String(BN_DIGITS.indexOf(c)));
  },
  group(n) {
    const v = Math.round(Number(n) || 0);
    return this.lang === "bn" ? v.toLocaleString("en-IN") : v.toLocaleString("en-US");
  },
  money(n) {
    if (n === null || n === undefined || Number.isNaN(Number(n))) return "–";
    const text = this.lang === "bn" ? `৳${this.group(n)}` : `BDT ${this.group(n)}`;
    return this.d(text);
  },
  num(n, decimals = 0) {
    if (n === null || n === undefined) return "–";
    const v = Number(n);
    const text = decimals ? v.toLocaleString(this.lang === "bn" ? "en-IN" : "en-US", { minimumFractionDigits: decimals, maximumFractionDigits: decimals }) : this.group(v);
    return this.d(text);
  },
  pct(fraction, decimals = 0) {
    return this.d(`${(Number(fraction) * 100).toFixed(decimals)}%`);
  },
  date(iso) {
    if (!iso) return "";
    const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
    return this.d(`${d} ${MONTHS[this.lang][m - 1]} ${y}`);
  },
  dayMonth(iso) {
    const [, m, d] = iso.slice(0, 10).split("-").map(Number);
    return this.d(`${d} ${MONTHS[this.lang][m - 1]}`);
  },
  range(a, b) {
    return `${this.dayMonth(a)} – ${this.dayMonth(b)}`;
  },
  shortRange(a, b) {
    const [, ma, da] = a.slice(0, 10).split("-").map(Number);
    const [, mb, db] = b.slice(0, 10).split("-").map(Number);
    const mon = MONTHS[this.lang];
    const short = (m) => (this.lang === "bn" ? mon[m - 1] : mon[m - 1]);
    return this.d(ma === mb ? `${da}–${db} ${short(mb)}` : `${da} ${short(ma)} – ${db} ${short(mb)}`);
  },
  monthName(ym) {
    const [y, m] = ym.split("-").map(Number);
    return this.d(`${MONTHS[this.lang][m - 1]} ${y}`);
  },
  weekLabel(label) {
    if (!label) return "";
    if (this.lang !== "bn") return label;
    const [mon, wk] = label.split(" ");
    const idx = MONTHS.en.indexOf(mon);
    return this.d(`${MONTHS.bn[idx]} সপ্তাহ-${wk.slice(1)}`);
  },
};
